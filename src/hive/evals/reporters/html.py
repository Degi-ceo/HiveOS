"""
html.py — single-file HTML reporter (no template engine, no JS framework).

The output is a self-contained HTML document that opens in any browser and
embeds every eval case: input, expected, actual output, grader verdict, and
timing. CI uploads this as a workflow artifact so reviewers can inspect a
failure without running the suite locally.

The HTML is generated by simple string concatenation — the report's structure
is small and predictable, so a Jinja dependency would be overkill.
"""
from __future__ import annotations

import html
from typing import IO

from hive.evals.types import EvalReport, EvalResult

_NAME = "html"


_TEMPLATE_HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Eval report — {dataset}</title>
<style>
  body {{ font-family: -apple-system, system-ui, sans-serif; margin: 24px; color: #1a1a1a; }}
  h1 {{ margin-bottom: 4px; }}
  .meta {{ color: #666; font-size: 13px; margin-bottom: 24px; }}
  .summary {{ display: flex; gap: 16px; margin-bottom: 32px; }}
  .summary > div {{ padding: 8px 16px; border-radius: 4px; background: #f4f4f4; }}
  .summary .pass {{ background: #d4edda; }}
  .summary .fail {{ background: #f8d7da; }}
  .summary .err  {{ background: #fff3cd; }}
  table {{ border-collapse: collapse; width: 100%; }}
  th, td {{ padding: 6px 10px; text-align: left; border-bottom: 1px solid #eee; font-size: 13px; vertical-align: top; }}
  th {{ background: #fafafa; }}
  tr.pass td.status {{ color: #155724; font-weight: bold; }}
  tr.fail td.status {{ color: #721c24; font-weight: bold; }}
  tr.err  td.status {{ color: #856404; font-weight: bold; }}
  pre {{ background: #f8f8f8; padding: 6px 8px; border-radius: 3px; white-space: pre-wrap; word-break: break-word; }}
  .all-pass {{ color: #155724; font-weight: bold; }}
  .any-fail {{ color: #721c24; font-weight: bold; }}
</style>
</head>
<body>
<h1>Eval report</h1>
<div class="meta">dataset: <code>{dataset}</code> · started {started} · finished {finished}</div>
<div class="summary">
  <div class="pass">passed: {passed}</div>
  <div class="fail">failed: {failed}</div>
  <div class="err">errored: {errored}</div>
  <div>total: {total}</div>
  <div>pass rate: {rate:.1f}%</div>
  <div>duration: {ms:.1f} ms</div>
</div>
<table>
  <thead><tr><th>#</th><th>id</th><th>grader</th><th>status</th><th>duration</th><th>input</th><th>expected</th><th>output</th><th>message</th></tr></thead>
  <tbody>
"""

_TEMPLATE_ROW = (
    "    <tr class=\"{css}\"><td>{idx}</td><td>{id_}</td><td>{grader}</td>"
    "<td class=\"status\">{status}</td><td>{ms:.1f} ms</td>"
    "<td><pre>{input_}</pre></td><td><pre>{expected}</pre></td><td><pre>{output}</pre></td>"
    "<td>{message}</td></tr>\n"
)


_TEMPLATE_FOOT = """  </tbody>
</table>
<p class="{verdict_class}">{verdict}</p>
</body>
</html>
"""


def render(report: EvalReport, stream: IO[str]) -> None:
    """Write a self-contained HTML report. Always pretty — never assumes
    a CSS framework is available."""
    s = report.summary
    head = _TEMPLATE_HEAD.format(
        dataset=html.escape(report.dataset_path),
        started=html.escape(report.started_at),
        finished=html.escape(report.finished_at),
        passed=s.passed,
        failed=s.failed,
        errored=s.errored,
        total=s.total,
        rate=s.pass_rate * 100,
        ms=s.total_duration_ms,
    )
    stream.write(head)
    for idx, r in enumerate(report.results, start=1):
        stream.write(_render_row(idx, r))
    verdict = "ALL PASSED" if s.all_passed else "EVALS FAILED"
    verdict_class = "all-pass" if s.all_passed else "any-fail"
    stream.write(_TEMPLATE_FOOT.format(verdict=verdict, verdict_class=verdict_class))


def _render_row(idx: int, r: EvalResult) -> str:
    if r.error is not None:
        status, css, message = "ERROR", "err", html.escape(r.error)
    elif r.passed:
        status, css, message = "PASS", "pass", html.escape(r.grader_result.message or "")
    else:
        status, css, message = "FAIL", "fail", html.escape(r.grader_result.message)
    return _TEMPLATE_ROW.format(
        idx=idx,
        id_=html.escape(r.item.id),
        grader=html.escape(r.item.grader),
        status=status,
        css=css,
        ms=r.duration_ms,
        input_=html.escape(r.item.input),
        expected=html.escape(r.item.expected),
        output=html.escape(r.output),
        message=message,
    )


def make() -> "HTMLReporter":
    return HTMLReporter()


class HTMLReporter:
    name = _NAME

    def write(self, report: EvalReport, stream: IO[str]) -> None:
        render(report, stream)
